
"""
Определение исключений подсистемы Kerberos-аутентификации.

Модуль содержит типизированные исключения, используемые
при проверке Kerberos-билетов и обработке протокола SPNEGO.

Иерархия исключений позволяет разделять:
- ошибки входных данных;
- ошибки проверки Kerberos-билета;
- незавершённый обмен токенами;
- ошибки конфигурации сервера;
- ошибки идентификации и допуска пользователя.

Требования безопасности:
Тексты исключений не должны содержать пароли, Kerberos-билеты,
содержимое keytab, идентификаторы сессий и другие секретные данные.
"""


class KerberosError(Exception):
    """
    Базовое исключение подсистемы Kerberos.

    Все пользовательские исключения Kerberos наследуются
    от этого класса. Позволяет централизованно обрабатывать
    ошибки Kerberos на уровне приложения.
    """


class KerberosAuthenticationError(KerberosError):
    """
    Ошибка выполнения Kerberos-аутентификации.

    Возможные причины:
    - недействительный или просроченный Kerberos-билет;
    - некорректный SPNEGO-токен;
    - ошибка установления контекста GSSAPI;
    - отсутствие подтверждённого Kerberos principal.

    Не следует использовать это исключение для обозначения
    ошибок конфигурации сервера.
    """


class KerberosTokenError(KerberosAuthenticationError):
    """
    Ошибка входящего HTTP Negotiate-токена.

    Возникает, если токен:
    - отсутствует;
    - имеет некорректный формат;
    - содержит недопустимые данные;
    - не может быть декодирован.
    """


class KerberosContextIncomplete(KerberosAuthenticationError):
    """
    Контекст GSSAPI ещё не установлен полностью.

    Незавершённый контекст не обязательно означает ошибку
    аутентификации. Для завершения SPNEGO-обмена серверу
    может потребоваться отправить клиенту промежуточный токен.
    """


class KerberosConfigurationError(KerberosError):
    """
    Ошибка конфигурации серверной части Kerberos.

    Возможные причины:
    - отсутствует keytab;
    - указан некорректный Service Principal Name (SPN);
    - недоступны Kerberos credentials;
    - отсутствует или некорректно настроен GSSAPI.

    Данное исключение обозначает эксплуатационную проблему
    сервера, а не ошибку учётных данных пользователя.
    """


class KerberosIdentityError(KerberosAuthenticationError):
    """
    Ошибка сопоставления Kerberos-идентичности с пользователем Django.

    Возникает, если Kerberos-аутентификация прошла успешно,
    но пользователь не может быть допущен к приложению.

    Возможные причины:
    - отсутствует соответствующая запись UserIdentity;
    - для пользователя запрещён вход через AD;
    - сотрудник не прошёл проверку допуска приложения.

    Это ошибка идентификации или авторизации на уровне
    приложения, а не ошибка проверки Kerberos-билета.
    """
